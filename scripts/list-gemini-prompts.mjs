// Run after `npm run build`: collects every <Image GeminiPrompt="..."> placeholder from the prerendered HTML
// and writes GEMINI-PROMPTS.md with the exact file path each generated image must be saved to.
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const appDir = path.join(root, ".next/server/app");
if (!fs.existsSync(appDir)) {
  console.error("Run `npm run build` first.");
  process.exit(1);
}
const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => (d.isDirectory() ? walk(path.join(dir, d.name)) : [path.join(dir, d.name)]));
const decode = (s) => s.replace(/&quot;/g, '"').replace(/&#x27;/g, "'").replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">");

const found = new Map();
for (const file of walk(appDir).filter((f) => f.endsWith(".html"))) {
  const html = fs.readFileSync(file, "utf8");
  const page = "/" + path.relative(appDir, file).replace(/\.html$/, "").replace(/(^|\/)index$/, "");
  for (const m of html.matchAll(/data-gemini-prompt="([^"]*)" data-gemini-file="([^"]*)" data-gemini-ratio="([^"]*)" data-gemini-size="([^"]*)"/g)) {
    const [prompt, target, ratio, size] = [decode(m[1]), decode(m[2]), m[3], m[4]];
    if (!found.has(target)) found.set(target, { prompt, ratio, size, pages: new Set() });
    found.get(target).pages.add(page === "/" ? "/" : page);
  }
}

const rows = [...found.entries()].sort(([a], [b]) => a.localeCompare(b));
const pending = rows.filter(([target]) => !fs.existsSync(path.join(root, "public", target)));
const out = [
  "# Gemini image prompts",
  "",
  "Generated by `node scripts/list-gemini-prompts.mjs`. Every GeminiPrompt is `image prompt | ratio | WIDTHxHEIGHT`.",
  "Generate each image at the listed size, save it as WebP at the path shown (under `public/`) and rebuild — the placeholder is replaced automatically.",
  "",
  `Total images: ${rows.length} · Still pending: ${pending.length}`,
  "",
  ...rows.map(([target, { prompt, ratio, size, pages }]) => `## ${fs.existsSync(path.join(root, "public", target)) ? "✅" : "⬜"} public${target}\n\n**GeminiPrompt:** ${prompt}\n\n**Ratio:** ${ratio} · **Size:** ${size.replace("x", " × ")} px\n\n**Used on:** ${[...pages].slice(0, 5).join(", ")}${pages.size > 5 ? ` (+${pages.size - 5} more)` : ""}\n`),
];
fs.writeFileSync(path.join(root, "GEMINI-PROMPTS.md"), out.join("\n"));
console.log(`Wrote GEMINI-PROMPTS.md — ${rows.length} images, ${pending.length} pending`);
